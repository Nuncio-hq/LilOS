/**
 * D-#817: Connect's refresh key for the bundled `lilos` plugin.
 *
 * `plugin.yaml`'s `version` stayed `0.2.0` through every catalog change, so
 * a profile whose copy still said 0.2.0 never recopied — new tools never
 * reached an existing install. The key is a sha256 over the directory the
 * app ships and copies (`packages/engine-hermes/plugin/lilos/`, and the
 * same tree under the app bundle's Resources). Relative paths are sorted
 * and written with `/`, then each file's bytes. Two directories match iff
 * those files match.
 *
 * Hermes writes `__pycache__` beside a loaded plugin. Those files are not
 * part of the ship, so they are skipped — counting them would recopy on
 * every start. `.DS_Store` is the same kind of noise. The recorded hash
 * (`lilos.content-hash`, a sibling of the installed directory) lives
 * outside the tree, so it is not an input and cannot be a fixed point.
 *
 * An empty directory is not a plugin. Hashing it as sha256("") would look
 * like a real install, and Connect would treat a missing ship as up to
 * date. `pluginContentHash` returns undefined for a missing, unreadable,
 * or empty tree (junk-only counts as empty) so nothing is copied.
 *
 * Not: the hand-bumped `version` string, hashing only `catalog.json`, or a
 * hash file inside the tree (it would be copied with the plugin).
 */
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync } from "node:fs";
import { basename, join, relative, sep } from "node:path";

/** Sibling of an installed `plugins/lilos` directory. The receipt Connect
 *  writes after a copy. Not an input to the hash. */
export const PLUGIN_CONTENT_HASH_FILE = "lilos.content-hash";

const SKIP_DIR = new Set(["__pycache__"]);
const SKIP_FILE = new Set([".DS_Store"]);

/** Sorted `/`-separated paths of the files the refresh key covers.
 *  Throws if `dir` cannot be read — callers that want "missing" use
 *  `pluginContentHash`, which turns that into undefined. */
export function listPluginFiles(dir: string): string[] {
  const out: string[] = [];
  const walk = (current: string): void => {
    for (const name of readdirSync(current)) {
      if (SKIP_DIR.has(name) || SKIP_FILE.has(name)) continue;
      const abs = join(current, name);
      const st = statSync(abs);
      if (st.isDirectory()) {
        walk(abs);
        continue;
      }
      if (!st.isFile()) continue;
      if (name.endsWith(".pyc")) continue;
      out.push(relative(dir, abs).split(sep).join("/"));
    }
  };
  walk(dir);
  out.sort();
  return out;
}

/** sha256 hex of sorted relative paths + contents. Undefined when `dir`
 *  is missing, not a directory, unreadable, or has no shipped files — a
 *  missing install is not an empty plugin, and an empty ship is not a
 *  hash Connect can match (D-#817). */
export function pluginContentHash(dir: string): string | undefined {
  try {
    if (!statSync(dir).isDirectory()) return undefined;
    const files = listPluginFiles(dir);
    if (files.length === 0) return undefined;
    const hash = createHash("sha256");
    for (const rel of files) {
      hash.update(rel);
      hash.update("\0");
      hash.update(readFileSync(join(dir, ...rel.split("/"))));
      hash.update("\0");
    }
    return hash.digest("hex");
  } catch {
    return undefined;
  }
}

/** `cpSync` filter. False skips the path. The same junk the hash ignores
 *  must not be copied into a profile or the app bundle — hashing skips it,
 *  but copying it still dirties the install (D-#817). */
export function pluginCopyFilter(src: string): boolean {
  const base = basename(src);
  if (SKIP_DIR.has(base) || SKIP_FILE.has(base)) return false;
  if (base.endsWith(".pyc")) return false;
  return true;
}

/** Committed manifest beside the shipped plugin (not inside it). The hex
 *  line is `pluginContentHash`; the paths are `listPluginFiles`. A plugin
 *  edit that does not regenerate this file fails `schema:check`. */
export function renderPluginHashManifest(dir: string): string {
  const hash = pluginContentHash(dir);
  if (hash === undefined)
    throw new Error(`plugin directory is not readable: ${dir}`);
  const files = listPluginFiles(dir);
  return [
    "# Generated by packages/engine-hermes/scripts/gen-plugin-hash.ts — do not edit.",
    hash,
    ...files,
    "",
  ].join("\n");
}
